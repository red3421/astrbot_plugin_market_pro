# 归一化：转成 dict 结构并补 id
NEWS = [
    {
        "id": i + 1,
        "tag": tag,
        "impact": float(impact),
        "title": title,
        "body": body,
    }
    for i, (tag, impact, title, body) in enumerate(_POOL)
]

TOTAL = len(NEWS)

TAG_ICON = {"利好": "🟢", "利空": "🔴", "中性": "⚪"}


def pick_news(symbol: str, day: str, count: int = 3) -> list:
    """同一天、同一币种抽到的资讯永远一致（用 symbol + 日期做种子）。"""
    if count <= 0:
        return []
    count = min(count, TOTAL)
    rng = random.Random("{}|{}|v1".format(day, str(symbol).upper()))
    idxs = rng.sample(range(TOTAL), count)
    return [dict(NEWS[i]) for i in idxs]


def total_impact(items) -> float:
    """把一组资讯的影响叠加起来（带边际递减，避免多条利好叠成暴涨）。"""
    positives = sum(x["impact"] for x in items if x["impact"] > 0)
    negatives = sum(x["impact"] for x in items if x["impact"] < 0)
    # 同向多条时按 0.75 递减叠加
    def shrink(v):
        if v == 0:
            return 0.0
        n = max(1, len([x for x in items if (x["impact"] > 0) == (v > 0) and x["impact"] != 0]))
        factor = sum(0.75 ** k for k in range(n)) / n if n else 1.0
        return v * factor

    return round(shrink(positives) + shrink(negatives), 6)


def summary_line(item) -> str:
    return "{} {}".format(TAG_ICON.get(item["tag"], "⚪"), item["title"])


def today_str() -> str:
    return date.today().isoformat()
